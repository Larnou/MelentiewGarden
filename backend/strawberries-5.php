            <p class="paragraph-6">1. На вспаханной или вскопанной деляне делаем разметку. Для гряд 80 см, для дорожки 40-50 см. Затем с дорожек землю скидываем на гряды и ровняем  граблями.  Почву хорошо пролить. Высаживать розетки будем в два ряда.</p>
            <p class="paragraph-6">2. Можно гряды огородить досками шириной 15 см. Расстояние между кустами  в  ряду 25-30 см в зависимости от сорта, а между рядами 30-40 см. Чтобы не полоть дорожки, положить,  например, черную пленку и засыпать ее свежими опилками, можно картон от коробок и засыпать опилками. Опилки пролить водой, чтобы не разнесло.  Очень красивые дорожки из кокосового волокна (продают в Леруа для ландшафтных  работ).</p>
            <p class="paragraph-6">3. На гряду, огороженную досками до высаживания растений расстилают черный укрывной материал, вырезают круги диаметром 10-17 см ( мы делаем 10 см) и закрепляют с боков П образными шпильками. Они продаются. Мы используем старые электроды для сварки.</p>
            <p class="paragraph-6">4. Высаживаем саженцы на бугры. Сначала делаем разметку для гряд 60см, для дорожек 50 см, с дорожек перекидываем землю. Грядки в итоге должны быть высотой 15-20 см. Разравниваем граблями и лучше немного утрамбовать. Для этого щит из фанеры длиной 1 м кладут на гряду и утаптывают, чтобы не было провалов. Затем расстилают на бугры черный укрывной материал, или агроткань, или черную пленку. Ширина этого укрытия должна закрывать саму гряду, бока гряды и половину дорожки. Другую половину дорожки закроем, укрывая другую гряду. Я разные гряды закрываю разными материалами, чтобы оценить, что лучше для моего участка, для нашего климата.</p>
